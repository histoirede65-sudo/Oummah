/** Interface text and language of the Prénoms module. */
export function usePrenomsText() {
  const { language } = useI18n();
  return useMemo(() => {
    const lang = prenomsLanguage(language);
    return { lang, tx: PRENOMS_TEXT[lang] };
  }, [language]);
}
