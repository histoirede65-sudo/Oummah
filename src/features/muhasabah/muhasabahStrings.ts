export function muhasabahText(language: LanguageCode) {
  const table = language === 'en' ? en : fr;
  return (key: MuhasabahStringKey, values?: Record<string, string | number>) =>
    table[key].replace(/\{(\w+)\}/g, (match, name: string) => (values && name in values ? String(values[name]) : match));
}

export function muhasabahLocale(language: LanguageCode) {
  return language === 'en' ? 'en-GB' : 'fr-FR';
}
