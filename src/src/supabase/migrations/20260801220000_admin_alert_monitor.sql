create or replace function public.admin_update_alert_setting(
  p_alert_type text,
  p_enabled boolean,
  p_critical_push_enabled boolean
)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not public.is_oummah_admin() then
    raise exception 'ADMIN_FORBIDDEN';
  end if;

  update public.admin_alert_settings
  set
    enabled = p_enabled,
    critical_push_enabled =
      case when p_enabled then p_critical_push_enabled else false end,
    updated_by = auth.uid(),
    updated_at = now()
  where alert_type = p_alert_type;

  if not found then
    raise exception 'ADMIN_ALERT_SETTING_NOT_FOUND';
  end if;

  if not p_enabled then
    update public.admin_system_alerts
    set
      status = 'ignored',
      ignored_at = now(),
      handled_by = auth.uid(),
      handling_note = 'Type d’alerte désactivé',
      updated_at = now()
    where alert_type = p_alert_type
      and status = 'open';
  end if;
end;
$$;

