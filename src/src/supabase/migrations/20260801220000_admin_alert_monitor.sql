-- OUMMAH — surveillance automatique des alertes
-- Exécution horaire avec pg_cron et push critique via pg_net.

create extension if not exists pg_cron with schema extensions;
create extension if not exists pg_net with schema extensions;

create table if not exists public.admin_alert_settings (
  alert_type text primary key,
  enabled boolean not null default true,
  critical_push_enabled boolean not null default true,
  label text not null,
  description text not null,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_alert_monitor_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running'
    check (status in ('running', 'success', 'failed')),
  open_alerts_before integer not null default 0,
  open_alerts_after integer not null default 0,
  new_critical_alerts integer not null default 0,
  push_requests_sent integer not null default 0,
  error_message text,
  created_at timestamptz not null default now()
);

create index if not exists admin_alert_monitor_runs_started_idx
on public.admin_alert_monitor_runs(started_at desc);

alter table public.admin_alert_settings enable row level security;
alter table public.admin_alert_monitor_runs enable row level security;

revoke all on public.admin_alert_settings from anon, authenticated;
revoke all on public.admin_alert_monitor_runs from anon, authenticated;

alter table public.admin_system_alerts
  add column if not exists push_notified_at timestamptz;

