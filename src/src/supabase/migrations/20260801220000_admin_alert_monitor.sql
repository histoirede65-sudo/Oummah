create or replace function public.admin_get_alert_monitor_health()
returns jsonb
language plpgsql
security definer
set search_path = public, auth, cron
as $$
declare
  last_run public.admin_alert_monitor_runs%rowtype;
  last_success_at timestamptz;
  last_failure_at timestamptz;
  cron_enabled boolean := false;
  cron_schedule text;
  calculated_status text;
begin
  if not public.is_oummah_admin() then
    raise exception 'ADMIN_FORBIDDEN';
  end if;

  select *
  into last_run
  from public.admin_alert_monitor_runs
  order by started_at desc
  limit 1;

  select max(finished_at)
  into last_success_at
  from public.admin_alert_monitor_runs
  where status = 'success';

  select max(finished_at)
  into last_failure_at
  from public.admin_alert_monitor_runs
  where status = 'failed';

  select
    job.active,
    job.schedule
  into cron_enabled, cron_schedule
  from cron.job job
  where job.jobname = 'oummah-admin-alert-monitor-hourly'
  limit 1;

  calculated_status :=
    case
      when last_run.id is null then 'never_run'
      when last_run.status = 'failed' then 'critical'
      when last_run.started_at < now() - interval '2 hours' then 'critical'
      when coalesce(cron_enabled, false) = false then 'warning'
      else 'healthy'
    end;

  return jsonb_build_object(
    'status', calculated_status,
    'last_run_at', last_run.started_at,
    'last_success_at', last_success_at,
    'last_failure_at', last_failure_at,
    'last_error', last_run.error_message,
    'cron_enabled', coalesce(cron_enabled, false),
    'cron_schedule', cron_schedule,
    'runs_24h', (
      select count(*)
      from public.admin_alert_monitor_runs
      where started_at >= now() - interval '24 hours'
    ),
    'failures_24h', (
      select count(*)
      from public.admin_alert_monitor_runs
      where started_at >= now() - interval '24 hours'
        and status = 'failed'
    )
  );
end;
$$;

create or replace function public.admin_list_alert_settings()
returns table (
  alert_type text,
  enabled boolean,
  critical_push_enabled boolean,
  label text,
  description text,
  updated_at timestamptz
)
